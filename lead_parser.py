def build_niches():
    """Каждая категория добирается гео-вариантами ровно до 40 ниш. Итого 1000."""
    niches = []
    for base in CLUSTERS:
        seen, out = set(), []
        for q in base:
            q = q.strip()
            if q and q.lower() not in seen:
                seen.add(q.lower())
                out.append(q)
        i = 0
        while len(out) < 40:
            q = f"{base[i % len(base)]} {GEO[(i // max(len(base), 1)) % len(GEO)]}"
            if q.lower() not in seen:
                seen.add(q.lower())
                out.append(q)
            i += 1
        niches.extend(out[:40])
    return niches


NICHES = build_niches()

