async def inspect_channel(client, niche, ch, max_subs):
    """Возвращает (row|None, причина пропуска)."""
    if not isinstance(ch, Channel) or not ch.username:
        return None, "не публичный"
    link = f"https://t.me/{ch.username}"
    title = (ch.title or "").strip()

    about = ""
    try:
        full = await client(functions.channels.GetFullChannelRequest(ch))
        about = (full.full_chat.about or "").strip()
        subs = full.full_chat.participants_count or 0
    except errors.ChannelPrivateError:
        return None, "закрыт"
    except errors.FloodWaitError as e:
        await asyncio.sleep(min(e.seconds + 1, 900))
        try:
            full = await client(functions.channels.GetFullChannelRequest(ch))
            about = (full.full_chat.about or "").strip()
            subs = full.full_chat.participants_count or 0
        except Exception:
            return None, "тг ограничил"

    # ── ГЛАВНОЕ В v3.7: фильтр по подписчикам ──
    if subs > max_subs:
        return None, f"крупный ({subs})"

    junk_text = f"{title} {about} {ch.username}"
    if any(rx.search(junk_text) for rx in JUNK_RES):
        return None, "мусор (агрегатор/вакансии)"

    # ── НОВОЕ В v3.7.3: салоны/студии/центры/сети — не один человек ──
    org_text = f"{title} {ch.username}"
    if any(rx.search(org_text) for rx in ORG_RES):
        return None, "мусор (заведение/сеть)"

    # свежие посты и сигналы в них
    texts = []
    now = datetime.now(timezone.utc)
    try:
        async for msg in client.iter_messages(ch, limit=30):
            if msg.message and msg.date:
                texts.append((msg.date, msg.message))
    except Exception:
        pass

    posts30 = sum(1 for d, _ in texts if d >= now - timedelta(days=30))
    posts60 = sum(1 for d, _ in texts if d >= now - timedelta(days=60))

    dlg_hit, dlg_date = None, None
    soft_hit, soft_date = None, None
    mention_count = 0
    for d, txt in texts:
        frag = find_signal(DIALOG_RES, txt)
        if frag:
            mention_count += 1
            if dlg_hit is None:
                dlg_hit, dlg_date = frag, d
        frag2 = find_signal(SOFT_RES, txt)
        if frag2:
            mention_count += 1
            if soft_hit is None:
                soft_hit, soft_date = frag2, d
    if dlg_hit is None:
        frag = find_signal(DIALOG_RES, f"{title} {about}")
        if frag:
            dlg_hit, dlg_date = frag, now
    if soft_hit is None:
        frag2 = find_signal(SOFT_RES, f"{title} {about}")
        if frag2:
            soft_hit, soft_date = frag2, now

    if posts60 == 0 and dlg_hit is None:
        return None, "мёртвый (нет постов 60 дней)"

    # факты
    facts = []
    if dlg_hit:
        facts.append(f"запись в переписку: «{dlg_hit}» ({dstr(dlg_date)})")
    elif soft_hit:
        facts.append(f"запись упомянута: «{soft_hit}» (телефон/админ)"
                     f" ({dstr(soft_date)})" if soft_date else
                     f"запись упомянута: «{soft_hit}» (телефон/админ)")
    facts.append(plural_posts(posts30))
    facts_txt = ", ".join(facts)

    # цитата — самый свежий пост
    quote = ""
    if texts:
        d0, t0 = texts[0]
        quote = f"{dstr(d0)}: «{re.sub(r'\s+', ' ', t0).strip()[:100]}»"

    # флаги
    flags = []
    if posts30 < 5:
        flags.append(f"мало постов ({posts30})")
    if posts60 == 0:
        flags.append("давно нет постов")
    if mention_count == 1:
        flags.append("запись упомянута 1 раз")
    if dlg_hit is None:
        flags.append("публичных фраз «запись в переписку» нет")
    flags_txt = ", ".join(flags)

    basket = "ПИСАТЬ СЕГОДНЯ" if (dlg_hit and posts30 >= 1) else "В ЗАПАСЕ"

    row = {"niche": niche, "title": title, "link": link, "subs": subs,
           "facts": facts_txt, "quote": quote, "flags": flags_txt,
           "basket": basket}
    return row, None


