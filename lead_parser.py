ORG_RES    = [re.compile(p, re.I) for p in ORG_RAW]


def find_signal(regexes, text):
    for rx in regexes:
        m = rx.search(text)
        if m:
            frag = re.sub(r"\s+", " ", m.group(0)).strip()
            return frag
    return None


def plural_posts(n):
    return f"{n} пост(ов) за последний месяц"


def dstr(dt):
    return dt.strftime("%d.%m.%y")


