async def run(max_subs):
    cfg = load_config()
    api_id = cfg.get("tg_api_id") or cfg.get("api_id")
    api_hash = cfg.get("tg_api_hash") or cfg.get("api_hash")
    try:
        api_id = int(api_id)
    except (TypeError, ValueError):
        api_id = None
    if not api_id or not api_hash:
        print(f"В {CONFIG_F} нет api_id/api_hash.")
        print("Заполните конфиг (api_id — число, api_hash — 32 символа из my.telegram.org)")
        sys.exit(1)

    prog = load_progress()
    pos, runs = int(prog.get("pos", 0)), int(prog.get("runs", 0))
    seen = load_seen_links()

    idxs = [(pos + k * STRIDE) % len(NICHES) for k in range(PER_RUN)]
    started = time.time()
    deadline = started + RUN_MINUTES * 60

    print("=" * 66)
    print(f"v3.7.3 «КАНАЛЫ, КОТОРЫМ НУЖНЫ БОТЫ» — порог подписчиков: до {max_subs}")
    print(f"Ниш в очереди: {len(NICHES)} | за прогон: {PER_RUN} | шаг: {STRIDE}")
    print(f"Прогресс: позиция {pos}, прогонов сделано {runs}")
    print("=" * 66)

    totals = {"проверено": 0, "в таблицу": 0, "крупные": 0, "мёртвые": 0,
              "мусор": 0, "прочее": 0, "дубли": 0}
    new_today = {"ПИСАТЬ СЕГОДНЯ": 0, "В ЗАПАСЕ": 0}

    client = TelegramClient(SESSION_F, api_id, api_hash)
    async with client:
        me = await client.get_me()
        if me is None:
            print("Сессия не авторизована — удалите lead_session.session*"
                  " и войдите заново по номеру телефона.")
            sys.exit(1)
        print(f"Вошли как: {me.first_name} (@{me.username})\n")

        for k, idx in enumerate(idxs, 1):
            if time.time() > deadline:
                print(f"\n⏱ Бюджет {RUN_MINUTES} мин исчерпан — позиция сохранена.")
                break
            niche = NICHES[idx]
            print(f"[{k:>2}/{PER_RUN}] ниша №{idx}: «{niche}»", end=" ")
            st = {"найдено": 0, "в таблицу": 0, "крупные": 0, "мёртвые": 0,
                  "мусор": 0, "дубли": 0, "прочее": 0}
            try:
                res = await client(functions.contacts.SearchRequest(
                    q=niche, limit=SEARCH_LIMIT))
                chats = [c for c in res.chats
                         if isinstance(c, Channel) and c.username]
                st["найдено"] = len(chats)
                for ch in chats[:MAX_PER_NICHE]:
                    if time.time() > deadline:
                        break
                    totals["проверено"] += 1
                    try:
                        row, why = await inspect_channel(client, niche, ch, max_subs)
                    except errors.FloodWaitError as e:
                        await asyncio.sleep(min(e.seconds + 1, 900))
                        row, why = None, "тг ограничил"
                    except Exception:
                        row, why = None, "прочее"
                    if row is None:
                        w = why or "прочее"
                        if w.startswith("крупный"):
                            st["крупные"] += 1; totals["крупные"] += 1
                        elif w.startswith("мёртв"):
                            st["мёртвые"] += 1; totals["мёртвые"] += 1
                        elif w.startswith("мусор"):
                            st["мусор"] += 1; totals["мусор"] += 1
                        else:
                            st["прочее"] += 1; totals["прочее"] += 1
                        continue
                    if row["link"].lower() in seen:
                        st["дубли"] += 1; totals["дубли"] += 1
                        continue
                    seen.add(row["link"].lower())
                    write_row(row)
                    st["в таблицу"] += 1
                    totals["в таблицу"] += 1
                    new_today[row["basket"]] += 1
            except errors.FloodWaitError as e:
                wait = min(e.seconds + 1, 900)
                print(f"— тг просит паузу {wait} с, жду…")
                await asyncio.sleep(wait)
                continue
            except Exception as e:
                print(f"— ошибка поиска: {type(e).__name__}")
                st["прочее"] += 1
            print(f"— найдено {st['найдено']}, в таблицу {st['в таблицу']}, "
                  f"мимо: крупные {st['крупные']}, мёртвые {st['мёртвые']}, "
                  f"мусор {st['мусор']}, дубли {st['дубли']}, прочее {st['прочее']}")

    pos_next = (pos + PER_RUN) % len(NICHES)
    runs += 1
    save_progress(pos_next, runs)

    print("\n" + "=" * 66)
    print("ИТОГ ПРОГОНА")
    print(f"  каналов проверено:        {totals['проверено']}")
    print(f"  новых записей в leads.csv:{totals['в таблицу']}"
          f" (ПИСАТЬ СЕГОДНЯ: {new_today['ПИСАТЬ СЕГОДНЯ']},"
          f" В ЗАПАСЕ: {new_today['В ЗАПАСЕ']})")
    print(f"  мимо крупные (>{max_subs} подп.): {totals['крупные']}")
    print(f"  мимо мёртвые:             {totals['мёртвые']}")
    print(f"  мимо мусор:               {totals['мусор']}")
    print(f"  мимо дубли:               {totals['дубли']}")
    print(f"  мимо прочее:              {totals['прочее']}")
    print(f"  прогресс: позиция {pos_next} из {len(NICHES)}"
          f" (прогон {runs}); файл leads.csv дополнен.")
    print("=" * 66)


def main():
    ap = argparse.ArgumentParser(description="Парсер каналов v3.7.1")
    ap.add_argument("--max", type=int, default=None,
                    help="порог подписчиков (по умолчанию 10000)")
    args = ap.parse_args()

    cfg = load_config()
    if args.max is not None:
        max_subs = args.max
    else:
        max_subs = int(cfg.get("max_subscribers", DEFAULT_MAX_SUBS))
    # пишем в конфиг только если он реально прочитался —
    # чтобы никогда не затирать файл с api-ключами пустышкой
    if cfg and "max_subscribers" not in cfg:
        cfg["max_subscribers"] = max_subs
        save_config(cfg)

    asyncio.run(run(max_subs))


if __name__ == "__main__":
    main()
