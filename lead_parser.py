def load_config():
    """Читает конфиг терпимо: utf-8/utf-8-sig/cp1251, вложенные ключи поднимает."""
    cfg = {}
    if os.path.exists(CONFIG_F):
        raw = open(CONFIG_F, "rb").read()
        for enc in ("utf-8-sig", "utf-8", "cp1251"):
            try:
                cfg = json.loads(raw.decode(enc))
                break
            except Exception:
                cfg = {}
    # если ключи лежат вложенно (например {"telegram": {...}}) — поднимем их
    if isinstance(cfg, dict) and not ("api_id" in cfg and "api_hash" in cfg):
        stack = [v for v in cfg.values() if isinstance(v, dict)]
        while stack:
            d = stack.pop()
            if "api_id" in d and "api_hash" in d:
                cfg["api_id"], cfg["api_hash"] = d["api_id"], d["api_hash"]
                break
            stack.extend(v for v in d.values() if isinstance(v, dict))
    return cfg


def save_config(cfg):
    if os.path.exists(CONFIG_F):
        shutil.copy2(CONFIG_F, CONFIG_F + ".bak-" + time.strftime("%Y%m%d_%H%M%S"))
    with open(CONFIG_F, "w", encoding="utf-8") as f:
        json.dump(cfg, f, ensure_ascii=False, indent=2)


def load_progress():
    if os.path.exists(PROGRESS_F):
        try:
            with open(PROGRESS_F, encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    return {"pos": 0, "runs": 0}


def save_progress(pos, runs):
    tmp = {"pos": pos % len(NICHES), "runs": runs, "updated": dstr(datetime.now())}
    with open(PROGRESS_F, "w", encoding="utf-8") as f:
        json.dump(tmp, f, ensure_ascii=False, indent=2)


def load_seen_links():
    seen = set()
    if os.path.exists(OUT_CSV):
        try:
            with open(OUT_CSV, encoding="utf-8-sig") as f:
                for row in csv.reader(f, delimiter=";"):
                    if len(row) >= 4 and row[3].startswith("http"):
                        seen.add(row[3].strip().lower())
        except Exception:
            pass
    return seen


def write_row(row):
    new_file = not os.path.exists(OUT_CSV)
    with open(OUT_CSV, "a", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f, delimiter=";")
        if new_file:
            w.writerow(["Ниша", "Платформа", "Название", "Ссылка", "Подписчики",
                        "Факты", "Пример цитаты", "Флаги", "Корзина"])
        w.writerow([row["niche"], "TG", row["title"], row["link"], row["subs"],
                    row["facts"], row["quote"], row["flags"], row["basket"]])


